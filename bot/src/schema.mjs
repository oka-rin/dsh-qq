/** path → field 的索引，保存时校验用 */
export const FIELD_BY_PATH = new Map(CONFIG_SCHEMA.flatMap((g) => g.fields.map((f) => [f.path, f])));

/** 按 'a.b.c' 取值；中间缺了算 undefined */
export function getByPath(obj, path) {
  return path.split('.').reduce((acc, key) => (acc == null ? undefined : acc[key]), obj);
}

/** 按 'a.b.c' 写值（中间对象不存在就建）；返回新的根对象（浅拷贝链上每一层） */
export function setByPath(obj, path, value) {
  const keys = path.split('.');
  const root = { ...(obj || {}) };
  let cur = root;
  for (let i = 0; i < keys.length - 1; i += 1) {
    const key = keys[i];
    const next = cur[key];
    cur[key] = next && typeof next === 'object' ? (Array.isArray(next) ? [...next] : { ...next }) : {};
    cur = cur[key];
  }
  cur[keys[keys.length - 1]] = value;
  return root;
}
