import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { Worker } from 'node:worker_threads';

const LIMIT = 8 * 1024 * 1024;
const CANCELLED = 'QQ 登录读取已取消';
const UNSUPPORTED = '窗口二维码不是已验证支持的 QQ 登录码；未向面板传送窗口截图';
const aborted = () => new Error(CANCELLED);

/** Binary, bounded and shell-free. Never include child output in errors. */
export function captureCommand(bin, args, { env = process.env, timeoutMs = 10000, maxBytes = LIMIT, maxStderrBytes = 65536, signal } = {}) {
  return new Promise((resolve, reject) => {
    if (signal?.aborted) return reject(aborted());
    let child, timer, settled = false, size = 0, stderrSize = 0;
    const chunks = [];
    const kill = () => {
      if (!child) return;
      // Do not kill a process group on platforms without POSIX group semantics.
      try { if (process.platform !== 'win32' && child.pid) process.kill(-child.pid, 'SIGKILL'); else child.kill('SIGKILL'); } catch { try { child.kill('SIGKILL'); } catch {} }
      child.stdout?.destroy(); child.stderr?.destroy();
    };
    const finish = (error, result) => {
      if (settled) return; settled = true;
      clearTimeout(timer); signal?.removeEventListener('abort', cancel);
      if (error) kill();
      chunks.length = 0;
      error ? reject(error) : resolve(result);
    };
    const cancel = () => finish(aborted());
    try { child = spawn(bin, args, { env, detached: process.platform !== 'win32', stdio: ['ignore', 'pipe', 'pipe'] }); }
    catch { finish(new Error('缺少窗口读取依赖或无执行权限')); return; }
    signal?.addEventListener('abort', cancel, { once: true });
    timer = setTimeout(() => finish(new Error('读取 QQ 登录窗口超时')), timeoutMs); timer.unref();
    child.stdout.on('data', data => {
      if (settled) return;
      size += data.length;
      if (size > maxBytes) finish(new Error('QQ 窗口数据过大')); else chunks.push(data);
    });
    child.stderr.on('data', data => { if (!settled && (stderrSize += data.length) > maxStderrBytes) finish(new Error('QQ 窗口命令错误输出过大')); });
    child.stdout.on('error', () => finish(new Error('无法读取 QQ 窗口数据')));
    child.stderr.on('error', () => finish(new Error('无法读取 QQ 窗口数据')));
    child.once('error', () => finish(new Error('缺少窗口读取依赖或无执行权限')));
    child.once('close', code => {
      if (settled) return;
      if (code !== 0) finish(new Error('无法读取 QQ 登录窗口；检查 QQ、显示环境和访问权限'));
      else finish(null, Buffer.concat(chunks, size));
    });
    if (signal?.aborted) cancel();
  });
}

/** These X11 properties are heuristics, not an adversarial X-client trust boundary. */
export function qqWindows(tree) {
  return [...String(tree).matchAll(/^\s*(0x[0-9a-f]+)\s+"(?:QQ|QQ登录|QQ 登录)":\s*\("qq"\s+"qq"\)\s+(\d+)x(\d+)(?:[+-]\d+){2}(?:\s|$)/gim)]
    .map(m => ({ id: String(parseInt(m[1], 16)), width: Number(m[2]), height: Number(m[3]) }))
    .filter(w => Number(w.id) > 0 && Number(w.id) <= 0xffffffff && w.width >= 240 && w.height >= 240 && w.width <= 2048 && w.height <= 2048);
}

function validatePng(png) {
  if (!Buffer.isBuffer(png) || png.length < 33 || png.length > LIMIT || png.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a' || png.readUInt32BE(8) !== 13 || png.toString('ascii', 12, 16) !== 'IHDR') throw new Error('QQ 窗口未返回有效图片');
  const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
  if (width < 240 || height < 240 || width > 2048 || height > 2048 || width * height > 4194304) throw new Error('QQ 窗口图片尺寸不符合限制');
  // Only the bounded noninterlaced 8-bit RGB/RGBA format generated by our FFmpeg.
  if (png[24] !== 8 || ![2, 6].includes(png[25]) || png[26] !== 0 || png[27] !== 0 || png[28] !== 0) throw new Error('QQ 窗口图片格式不受支持');
}

/** Decode in a terminable worker; never return source pixels, decoded URLs or decoder errors. */
export async function loginQr(png, { signal, timeoutMs = 6000 } = {}) {
  validatePng(png);
  if (signal?.aborted) throw aborted();
  return new Promise((resolve, reject) => {
    let worker, timer, settled = false;
    const finish = (error, image) => {
      if (settled) return; settled = true;
      clearTimeout(timer); signal?.removeEventListener('abort', cancel);
      worker?.terminate().catch(() => {});
      error ? reject(error) : resolve(image);
    };
    const cancel = () => finish(aborted());
    try { worker = new Worker(new URL('./login-worker.js', import.meta.url), { workerData: png, execArgv: [], resourceLimits: { maxOldGenerationSizeMb: 128, maxYoungGenerationSizeMb: 32, stackSizeMb: 4 } }); }
    catch { finish(new Error('无法启动 QQ 二维码识别')); return; }
    signal?.addEventListener('abort', cancel, { once: true });
    timer = setTimeout(() => finish(new Error('QQ 二维码识别超时')), timeoutMs); timer.unref();
    worker.once('error', () => finish(new Error('QQ 二维码识别失败')));
    worker.once('exit', () => finish(new Error('QQ 二维码识别未完成')));
    worker.once('message', result => {
      if (result?.ok === true && typeof result.image === 'string' && /^data:image\/png;base64,[A-Za-z0-9+/=]+$/.test(result.image) && result.image.length <= 262144) finish(null, result.image);
      else finish(new Error(result?.reason === 'missing' ? 'QQ 窗口中没有可识别的登录二维码；请在 QQ 登录页显示二维码后重新读取' : UNSUPPORTED));
    });
    if (signal?.aborted) cancel();
  });
}

function cancellable(promise, signal) {
  return new Promise((resolve, reject) => {
    const cancel = () => reject(aborted());
    if (signal.aborted) { reject(aborted()); return; }
    signal.addEventListener('abort', cancel, { once: true });
    Promise.resolve(promise).then(resolve, reject).finally(() => signal.removeEventListener('abort', cancel));
  });
}

export function createLogin({ mode = 'native', container = 'snowluma', display = ':99', xauthority = '/var/lib/snowluma/.Xauthority', check, run = captureCommand, decode = loginQr, now = Date.now }) {
  if (!/^:[0-9]{1,4}(?:\.[0-9])?$/.test(display)) throw new Error('登录显示地址必须是本机 X11 显示编号');
  if (!/^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,127}$/.test(container)) throw new Error('登录读取的容器名无效');
  if (xauthority && (!path.isAbsolute(xauthority) || /[\r\n\0]/.test(xauthority))) throw new Error('Xauthority 必须是本机绝对路径');
  let capturedAt = null, busy = false, disposed = false;
  const lifetime = new AbortController();
  const selectedDisplay = mode === 'docker' ? ':1' : display;
  const alive = () => { if (disposed) throw new Error('插件已卸载，登录读取已取消'); };
  const operationSignal = signal => AbortSignal.any([lifetime.signal, AbortSignal.timeout(25000), ...(signal ? [signal] : [])]);
  const exec = async (bin, args, signal, options = {}) => {
    alive(); if (signal.aborted) throw aborted();
    const env = { ...process.env, DISPLAY: selectedDisplay };
    if (mode !== 'docker' && xauthority) {
      if (!fs.existsSync(xauthority)) throw new Error('未找到所选 QQ 显示的 Xauthority；请检查受保护的显示配置');
      env.XAUTHORITY = xauthority;
    }
    const result = mode === 'docker'
      ? run('docker', ['exec', '-e', `DISPLAY=${selectedDisplay}`, container, 'timeout', '--signal=KILL', '8s', bin, ...args], { ...options, timeoutMs: 9000, signal })
      : run(bin, args, { ...options, timeoutMs: 9000, env, signal });
    const output = await cancellable(result, signal);
    alive(); if (signal.aborted) throw aborted();
    return output;
  };
  const discover = async signal => {
    const tree = (await exec('xwininfo', ['-root', '-tree'], signal, { maxBytes: 256 * 1024 })).toString('utf8');
    const windows = qqWindows(tree);
    if (windows.length !== 1) throw new Error(windows.length ? '发现多个 QQ 窗口；请保留一个待登录实例后重试' : '未找到 QQ 登录窗口；请先启动所选后端并打开 QQ 二维码页');
    const selected = windows[0];
    const props = (await exec('xprop', ['-id', selected.id, '_NET_WM_PID', 'WM_CLASS'], signal, { maxBytes: 8192 })).toString('utf8');
    const pid = props.match(/^_NET_WM_PID\(CARDINAL\)\s*=\s*([1-9][0-9]{0,9})\s*$/m);
    if (!pid || !/^WM_CLASS\(STRING\)\s*=\s*"qq",\s*"qq"\s*$/im.test(props)) throw new Error('无法核实 QQ 窗口归属；未截取桌面');
    const exe = (await exec('readlink', ['-f', `/proc/${pid[1]}/exe`], signal, { maxBytes: 4096 })).toString('utf8').trim();
    const allowed = mode === 'docker' ? ['/opt/QQ/qq'] : ['/opt/QQ/qq', '/opt/snowluma/qq/qq'];
    if (!allowed.includes(exe)) throw new Error('窗口进程不是受信任路径的 QQ；未截取桌面');
    // Recheck server state after process lookup, before giving the XID to a consumer.
    const current = qqWindows((await exec('xwininfo', ['-root', '-tree'], signal, { maxBytes: 256 * 1024 })).toString('utf8'));
    if (current.length !== 1 || current[0].id !== selected.id || current[0].width !== selected.width || current[0].height !== selected.height) throw new Error('QQ 窗口已变化，请重新读取');
    return selected;
  };
  async function exclusive(signal, task) {
    alive();
    if (busy) throw new Error('正在读取登录窗口，请稍后再试');
    if (!['native', 'docker'].includes(mode)) throw new Error('外部网关不支持读取本机 QQ 窗口；请在其受保护的桌面扫码');
    busy = true;
    try { return await task(operationSignal(signal)); }
    finally { busy = false; }
  }
  async function status({ signal } = {}) {
    alive();
    const probeSignal = AbortSignal.any([lifetime.signal, AbortSignal.timeout(14000), ...(signal ? [signal] : [])]);
    if (probeSignal.aborted) throw aborted();
    const common = { ok: true, capturedAt, expiryUnknown: true, canRefresh: false, canCapture: ['native', 'docker'].includes(mode), mode, selectedClientVerified: false };
    try {
      const connected = await cancellable(Promise.resolve().then(() => check({ signal: probeSignal })), probeSignal);
      alive();
      if (!connected || connected.ok === false) throw new Error('gateway unavailable');
      return { ...common, state: 'logged_in', gatewayReady: true, account: connected.account, websocket: connected.websocket, source: 'configured-onebot', reason: '仅确认当前配置的 OneBot 账号和连接可用；不证明所选 QQ 窗口已登录，也不证明原生迁移完成。仍可显式读取所选窗口。' };
    } catch {
      alive(); if (signal?.aborted) throw aborted();
      return { ...common, state: capturedAt !== null ? 'qr_captured' : 'unavailable', gatewayReady: false, source: 'qq-window', reason: '当前配置的 OneBot 尚未就绪；可能是未登录、未注入、端口、Token 或事件连接问题。曾读取的二维码是否过期未知，重新读取不会更新二维码。' };
    }
  }
  async function window({ signal } = {}) {
    return exclusive(signal, async active => {
      const selected = await discover(active);
      return { id: selected.id, width: selected.width, height: selected.height, display: selectedDisplay, source: 'qq-window', mode };
    });
  }
  async function qr({ signal } = {}) {
    return exclusive(signal, async active => {
      capturedAt = null;
      // An old configured gateway must never suppress explicit capture of the selected backend.
      const selected = await discover(active);
      const png = await exec('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-nostdin', '-f', 'x11grab', '-draw_mouse', '0', '-framerate', '1', '-video_size', `${selected.width}x${selected.height}`, '-window_id', selected.id, '-i', selectedDisplay, '-frames:v', '1', '-threads', '1', '-f', 'image2pipe', '-vcodec', 'png', '-pix_fmt', 'rgba', 'pipe:1'], active);
      let image;
      try { image = await cancellable(decode(png, { signal: active }), active); }
      catch { alive(); if (active.aborted) throw aborted(); throw new Error('QQ 登录码未识别或格式不受支持；未向面板传送窗口截图'); }
      alive(); if (active.aborted) throw aborted();
      capturedAt = now();
      return { ok: true, state: 'qr_captured', source: 'qq-window', image, capturedAt, expiryUnknown: true, canRefresh: false,
        reason: '这是 QQ 窗口当前显示的登录码，是否过期未知；重新读取不会更新过期二维码。请用手机 QQ 扫码并亲自确认。' };
    });
  }
  return { status, qr, window, refresh: async () => { alive(); throw new Error('原版 SnowLuma 没有更新 QQ 二维码接口；请在 QQ 桌面点击更新后重新读取，插件不会重启 QQ 或自动点击登录确认'); }, dispose: () => { disposed = true; capturedAt = null; lifetime.abort(); } };
}

/** Additional browser CSRF guard; authenticated connection rejection belongs to the route. */
export function assertLoginRequest(req, { trustedOrigin } = {}) {
  if (req.method !== 'POST') throw new Error('只接受 POST');
  if (!/^application\/json(?:\s*;|$)/i.test(String(req.headers?.['content-type'] || ''))) throw new Error('登录读取只接受 JSON 请求');
  const site = req.headers?.['sec-fetch-site'];
  if (site && !['same-origin', 'none'].includes(site)) throw new Error('拒绝跨站登录读取');
  const origin = req.headers?.origin;
  if (!origin) throw new Error('登录读取需要浏览器同源请求');
  let url; try { url = new URL(origin); } catch { throw new Error('无效请求来源'); }
  const protocol = req.socket?.encrypted ? 'https:' : 'http:';
  let expected = `${protocol}//${req.headers.host}`;
  // Only pass trustedOrigin AFTER the authenticated Connection service has validated
  // the request. Never derive this override from unvalidated forwarded headers.
  if (trustedOrigin !== undefined) {
    let trusted; try { trusted = new URL(trustedOrigin); } catch { throw new Error('无效可信来源'); }
    if (!['http:', 'https:'].includes(trusted.protocol) || trusted.host !== req.headers.host || trusted.username || trusted.password || trusted.pathname !== '/' || trusted.search || trusted.hash) throw new Error('无效可信来源');
    expected = trusted.origin;
  }
  if (!['http:', 'https:'].includes(url.protocol) || url.origin !== expected || url.host !== req.headers.host || url.username || url.password || url.pathname !== '/' || url.search || url.hash) throw new Error('拒绝非同源登录读取');
}
